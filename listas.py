#indice 0, 1, 2, 3, 4, 5

# crear una lista vacía
aprendices = []

#crear una lista con elementos
aprendices = ["Juan", "Leidy", "Daniel", "Simon", "Lucho"]
print(aprendices)

#Acceder a elementos de la lista
print(aprendices[1]) # Leidy

#Modificar un elemento de la lista
aprendices[2] = "Camilo"
print(aprendices)
# consultar rangos de elementos de la lista
print(aprendices[1:4]) # Leidy, Camilo, Simon
