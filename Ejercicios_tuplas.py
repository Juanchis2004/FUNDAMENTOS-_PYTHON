# Ejercicio 1: Producto escalar de dos tuplas
vector1 = (1, 2, 3)
vector2 = (-1, 0, 2)

producto_escalar = vector1[0]*vector2[0] + vector1[1]*vector2[1] + vector1[2]*vector2[2]
print("Producto escalar:", producto_escalar)

# Ejercicio 2: Menor y mayor precio en una lista
precios = [50, 75, 46, 22, 80, 65, 8]

menor = min(precios)
mayor = max(precios)

print("Menor precio:", menor)
print("Mayor precio:", mayor)
